"""Exercise the guard against real temporary Git indexes and commits."""
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[2]
CHECKER = ROOT / "tooling/check_code_size.py"
LIMIT = 20 * 1024


class CodeSizeHookTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.repo = Path(self.temp.name)
        self.env = os.environ.copy()
        # A test run inside a hook must not inherit the parent repository index.
        for key in list(self.env):
            if key.startswith("GIT_"):
                self.env.pop(key)
        self.env.update(PYTHONUTF8="1", GIT_CONFIG_NOSYSTEM="1")
        self.git("init", "-q")
        self.git("config", "user.name", "ACAurafly")
        self.git("config", "user.email", "ACAurafly@users.noreply.github.com")
        self.git("config", "core.autocrlf", "false")
        self.git("config", "core.hooksPath", ".test-hooks")
        self.git("config", "commit.gpgsign", "false")

    def git(self, *args, check=True):
        return subprocess.run(["git", *args], cwd=self.repo, env=self.env,
                              capture_output=True, check=check)

    def stage(self, name, content):
        path = self.repo / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)
        self.git("add", "--", name)

    def guard(self, code=0):
        result = subprocess.run([sys.executable, str(CHECKER)], cwd=self.repo,
                                env=self.env, capture_output=True)
        self.assertEqual(result.returncode, code, result.stderr.decode("utf-8"))
        return result.stderr.decode("utf-8")

    def test_threshold_and_all_violations(self):
        self.stage("exact.py", b"#" * LIMIT)
        self.guard()
        for name in ("space name.py", "中文.ts"):
            self.stage(name, b"x" * (LIMIT + 1))
        error = self.guard(1)
        for value in ("space name.py", "中文.ts", "20481", "20480", "请按功能拆分"):
            self.assertIn(value, error)

    def test_uses_index_in_both_partial_staging_directions(self):
        self.stage("partial.py", b"x" * (LIMIT + 1))
        (self.repo / "partial.py").write_bytes(b"small")
        self.guard(1)
        self.stage("partial.py", b"small")
        (self.repo / "partial.py").write_bytes(b"x" * (LIMIT + 1))
        self.guard()

    def test_excluded_artifacts_and_generated_headers(self):
        names = ("pnpm-lock.yaml", "package-lock.json", "Cargo.lock", "uv.lock",
                 "doc.md", "fixture.json", "image.png", "vendor/lib.py",
                 "third_party/lib.cpp", "dist/app.js", "node_modules/lib.js",
                 "types.generated.d.ts", "api.generated.ts", "api.g.cs", "bundle.min.js",
                 "messages_pb2.py", "generated/api.py")
        for name in names:
            self.stage(name, b"x" * (LIMIT + 1))
        for i, header in enumerate((b"# Generated by protoc. DO NOT EDIT.\n",
                                    b"// Code generated by tool. DO NOT EDIT.\n",
                                    b"/* @generated */\n")):
            self.stage(f"header{i}.py", header + b"x" * LIMIT)
        self.guard()

    def test_staged_attributes_control_exclusions(self):
        self.stage(".gitattributes", b"api.py linguist-generated=true\nlib.py linguist-vendored\n")
        self.stage("api.py", b"x" * (LIMIT + 1))
        self.stage("lib.py", b"x" * (LIMIT + 1))
        (self.repo / ".gitattributes").write_text("", encoding="utf-8")
        self.guard()
        self.stage(".gitattributes", b"api.py -linguist-generated\nlib.py linguist-vendored=false\n")
        self.guard(1)

    def test_deleted_and_unchanged_large_files_do_not_block(self):
        self.stage("old.py", b"x" * (LIMIT + 1))
        self.git("commit", "-qm", "baseline", "--no-verify")
        self.stage("small.py", b"small")
        self.guard()
        self.git("rm", "old.py")
        self.guard()

    def test_rename_to_source_is_checked(self):
        self.stage("large.txt", b"x" * (LIMIT + 1))
        self.git("commit", "-qm", "baseline")
        self.git("mv", "large.txt", "large.py")
        self.guard(1)

    def test_source_string_mentioning_generation_is_not_exempt(self):
        self.stage("manual.py", b'text = "generated by tool"\n' + b"x" * LIMIT)
        self.guard(1)

    def test_handwritten_type_declarations_are_code(self):
        self.stage("types.d.ts", b"x" * (LIMIT + 1))
        self.guard(1)

    def test_empty_index_and_git_errors(self):
        self.guard()
        outside = self.repo / "outside"
        outside.mkdir()
        # Force Git to fail rather than discover the temporary parent repository.
        env = dict(self.env, GIT_DIR=str(outside / "missing.git"))
        result = subprocess.run([sys.executable, str(CHECKER)], cwd=outside,
                                env=env, capture_output=True)
        self.assertEqual(result.returncode, 1)
        self.assertIn("已阻止提交", result.stderr.decode("utf-8"))

    def test_symlink_mode_is_skipped(self):
        # Populate the index directly so Windows needs no symlink privilege.
        oid = subprocess.run(["git", "hash-object", "-w", "--stdin"],
                             input=b"x" * (LIMIT + 1), cwd=self.repo,
                             env=self.env, capture_output=True, check=True).stdout.strip()
        self.git("update-index", "--add", "--cacheinfo",
                 "120000", oid.decode("ascii"), "link.py")
        self.guard()

    def test_utf8_is_measured_in_bytes(self):
        self.stage("unicode.py", ("#" + "中" * 7000).encode("utf-8"))
        self.assertIn("21001", self.guard(1))

    def test_all_audits_untracked_worktree_and_preserves_frozen_evidence(self):
        (self.repo / "local.py").write_bytes(b"x" * (LIMIT + 1))
        def audit():
            return subprocess.run([sys.executable, str(CHECKER), "--all"], cwd=self.repo,
                                  env=self.env, capture_output=True)
        self.assertEqual(audit().returncode, 1)
        # These are local (unstaged) attributes, unlike the commit check.
        (self.repo / ".gitattributes").write_text(
            "local.py xdance-code-size-snapshot=true\n", encoding="utf-8")
        self.assertEqual(audit().returncode, 0)
        self.stage("local.py", b"x" * (LIMIT + 1))
        self.guard(1)
        self.git("add", ".gitattributes")
        self.guard()

    def test_xml_reports_and_diagrams_are_data(self):
        self.stage("report.xml", b"x" * (LIMIT + 1))
        self.guard()

    def test_real_commit_runs_hook(self):
        (self.repo / "tooling").mkdir()
        shutil.copyfile(CHECKER, self.repo / "tooling/check_code_size.py")
        hooks = self.repo / ".test-hooks"
        hooks.mkdir()
        hook = hooks / "pre-commit"
        shutil.copyfile(ROOT / ".githooks/pre-commit", hook)
        hook.chmod(0o755)
        self.stage("large.py", b"x" * (LIMIT + 1))
        result = self.git("commit", "-qm", "reject", check=False)
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("请按功能拆分", result.stderr.decode("utf-8"))
        self.stage("large.py", b"small")
        self.git("commit", "-qm", "allow")


if __name__ == "__main__":
    unittest.main()
