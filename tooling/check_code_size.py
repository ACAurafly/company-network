"""Reject oversized staged, human-maintained source files (stdlib only)."""
from __future__ import annotations

import fnmatch
import os
from pathlib import Path, PurePosixPath
import re
import subprocess
import sys

LIMIT = 20 * 1024
SOURCE_SUFFIXES = frozenset("""
.py .pyi .pyw .js .jsx .mjs .cjs .ts .tsx .mts .cts .vue .svelte
.c .h .cc .hh .cpp .hpp .cxx .hxx .cs .java .kt .kts .scala .go .rs
.swift .m .mm .rb .php .lua .r .jl .pl .pm .sh .bash .zsh .fish
.ps1 .psm1 .psd1 .bat .cmd .sql .css .scss .sass .less .html .htm
.xaml .uxml .uss .shader .hlsl .glsl .wgsl .cg .compute .gd .ex .exs
.erl .hrl .clj .cljs .dart .vb .fs .fsx .proto .graphql .gql
""".split())
ARTIFACT_DIRS = frozenset({
    "node_modules", "vendor", "third_party", "third-party", "generated",
    "__generated__", "dist", "build", ".venv", "venv", "__pycache__",
})
ARTIFACT_NAMES = (
    "*.lock", "*-lock.*", "*.min.*", "*.generated.*", "*.g.cs", "*.g.i.cs",
    "*.designer.cs", "*_pb2.py",
    "*_pb2_grpc.py", "*.pb.go", "*.pb.cc", "*.pb.h",
)
GENERATED_COMMENT = re.compile(
    rb"^\s*(?:\#|//|/\*|\*|<!--|--)\s*"
    rb"(?:@generated\b|<auto-generated\b|(?:code\s+)?generated\s+by\b|"
    rb"automatically\s+generated\b|auto[- ]generated\b|do\s+not\s+edit\b)",
    re.I | re.M,
)


def git(*args: str, data: bytes | None = None) -> bytes:
    return subprocess.run(["git", *args], input=data, stdout=subprocess.PIPE,
                          stderr=subprocess.PIPE, check=True).stdout


def source_candidate(path: str) -> bool:
    file = PurePosixPath(path.lower())
    if any(part in ARTIFACT_DIRS for part in file.parts[:-1]):
        return False
    if any(fnmatch.fnmatchcase(file.name, pattern) for pattern in ARTIFACT_NAMES):
        return False
    return (file.suffix in SOURCE_SUFFIXES or file.name in {
        "dockerfile", "makefile", "gnumakefile", "cmakelists.txt",
    } or path.startswith(".githooks/"))


def excluded_paths(raw_paths: list[bytes], *, cached: bool) -> set[bytes]:
    attributes = git("check-attr", *(["--cached"] if cached else []), "-z", "--stdin",
                     "linguist-generated", "linguist-vendored", "xdance-code-size-snapshot",
                     data=b"\0".join(raw_paths) + b"\0")
    values = attributes.split(b"\0")
    return {path for path, _, value in zip(values[0::3], values[1::3], values[2::3])
            if value.lower() in {b"set", b"true"}}


def report(violations: list[tuple[str, int]]) -> int:
    if not violations:
        return 0
    print(f"检查被拦截：代码文件超过 20KB（{LIMIT} 字节）：", file=sys.stderr)
    for path, size in violations:
        print(f"  {path!r}: {size} 字节", file=sys.stderr)
    print("请按功能拆分为职责明确的小文件，再重新暂存并提交。", file=sys.stderr)
    return 1


def check_worktree() -> int:
    """Audit tracked and non-ignored untracked local files using local attributes."""
    root = os.fsdecode(git("rev-parse", "--show-toplevel").rstrip(b"\r\n"))
    os.chdir(root)
    paths = sorted(set(git("ls-files", "-co", "--exclude-standard", "-z").split(b"\0")) - {b""})
    candidates = [raw for raw in paths if source_candidate(os.fsdecode(raw))]
    if not candidates:
        return 0
    excluded = excluded_paths(candidates, cached=False)
    violations = []
    for raw in candidates:
        path = Path(os.fsdecode(raw))
        if raw in excluded or path.is_symlink() or not path.is_file():
            continue
        size = path.stat().st_size
        if size > LIMIT:
            with path.open("rb") as source:
                header = source.read(4096).removeprefix(b"\xef\xbb\xbf")
            if not GENERATED_COMMENT.search(header):
                violations.append((path.as_posix(), size))
    result = report(violations)
    if result == 0:
        print(f"本地代码体积检查通过（{len(paths)} 个文件，0 个手写代码文件超过 {LIMIT} 字节）。")
    return result


def check() -> int:
    # NUL delimiters preserve whitespace, non-ASCII and newline-containing paths.
    fields = git("diff", "--cached", "--raw", "-z", "--no-renames",
                 "--no-ext-diff", "--no-abbrev", "--diff-filter=ACMT").split(b"\0")
    candidates = []
    for metadata, raw_path in zip(fields[0::2], fields[1::2]):
        _, mode, _, oid, _ = metadata.split()
        path = os.fsdecode(raw_path)
        if mode in {b"100644", b"100755"} and source_candidate(path):
            candidates.append((path, raw_path, oid.decode("ascii")))
    if not candidates:
        return 0

    excluded = excluded_paths([item[1] for item in candidates], cached=True)
    violations = []
    for path, raw_path, oid in candidates:
        if raw_path in excluded:
            continue
        size = int(git("cat-file", "-s", oid))
        if size <= LIMIT:
            continue
        header = git("cat-file", "blob", oid)[:4096].removeprefix(b"\xef\xbb\xbf")
        if not GENERATED_COMMENT.search(header):
            violations.append((path, size))
    return report(violations)


def main() -> int:
    if hasattr(sys.stderr, "reconfigure"):
        sys.stderr.reconfigure(encoding="utf-8", errors="backslashreplace")
    try:
        if sys.argv[1:] == ["--all"]:
            return check_worktree()
        if sys.argv[1:]:
            raise ValueError("用法：python tooling/check_code_size.py [--all]")
        return check()
    except (OSError, ValueError, subprocess.CalledProcessError) as exc:
        detail = (exc.stderr.decode("utf-8", errors="replace")
                  if isinstance(exc, subprocess.CalledProcessError) else str(exc))
        print(f"代码体积检查失败，已阻止提交：{detail}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
